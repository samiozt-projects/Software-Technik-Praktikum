package scenes

import config.ConfigManager
import domain.ConnectionState
import network.CreateWorldDTO
import network.TrafficSimRestClient
import network.ServerConnection
import network.WorldPropertiesDTO
import persistence.WorldLevelSelection
import java.io.IOException

/**
 * Result of fetching the server's world list for [WorldSelectionScene].
 */
internal sealed class ServerWorldsResult {
    /**
     * Worlds successfully fetched and parsed from the server.
     *
     * @property worlds the fetched worlds, mapped to selection-menu rows newest first.
     */
    data class Success(val worlds: List<WorldSelectionScene.WorldEntry>) : ServerWorldsResult()

    /**
     * The fetch failed; shown instead of crashing.
     *
     * @property message user-facing message describing why no server worlds are shown.
     */
    data class Failure(val message: String) : ServerWorldsResult()
}

/**
 * Result of deleting one world on the server for [WorldSelectionScene].
 */
internal sealed class ServerWorldDeleteResult {
    /** The world was deleted on the server. */
    object Success : ServerWorldDeleteResult()

    /**
     * The delete request failed; shown instead of crashing.
     *
     * @property message user-facing message describing why the world could not be deleted.
     */
    data class Failure(val message: String) : ServerWorldDeleteResult()
}

/**
 * Result of creating one world on the server for [WorldSelectionScene].
 */
internal sealed class ServerWorldCreateResult {
    /**
     * The world was created on the server.
     *
     * @property worldId ID generated by the server for the new world.
     */
    data class Success(val worldId: String) : ServerWorldCreateResult()

    /**
     * The create request failed; shown instead of crashing.
     *
     * @property message user-facing message describing why the world could not be created.
     */
    data class Failure(val message: String) : ServerWorldCreateResult()
}

/**
 * Fetches and parses the coupling server's world list for [WorldSelectionScene].
 *
 * Kept separate from scene rendering so the fetch/parse logic can be unit-tested without the
 * KorGE view-test harness. Only `GET /worlds` is used — the server's neutral (table-unassigned)
 * sources reachable through the fields/sources endpoints are intentionally never fetched or
 * merged into the selection list.
 */
internal object WorldSelectionServerLoader {

    /** Shown when table coupling is disabled outright via [ConfigManager.NetworkConfig.active]. */
    const val SERVER_DISABLED_MESSAGE = "Serververbindung ist deaktiviert."

    /** Shown when coupling is enabled but the table has not connected to the server yet. */
    const val NOT_CONNECTED_MESSAGE = "Nicht mit dem Server verbunden. Bitte zuerst im Server-Menü verbinden."

    /** Shown when the server could not be reached or returned an unusable response. */
    const val CONNECTION_ERROR_MESSAGE =
        "Welten konnten nicht vom Server geladen werden. Bitte Verbindung prüfen und erneut versuchen."

    /** Shown when a world could not be deleted because the delete request failed. */
    const val DELETE_ERROR_MESSAGE =
        "Welt konnte nicht gelöscht werden. Bitte Verbindung prüfen und erneut versuchen."

    /** Shown when a new world could not be created because the create request failed. */
    const val CREATE_ERROR_MESSAGE =
        "Welt konnte nicht erstellt werden. Bitte Verbindung prüfen und erneut versuchen."

    /**
     * Fixed grid size used when creating a new world via "Neue Welt erstellen".
     *
     * The local world editor does not yet expose column/row/field-size inputs (planned for the
     * "Welt-Editor" issue #227), so every newly created world uses this minimal server-valid grid
     * (columns/rows must be 2-10, field size 10-200) until that editor exists.
     */
    private const val NEW_WORLD_COLUMNS = 2
    private const val NEW_WORLD_ROWS = 2
    private const val NEW_WORLD_FIELD_SIZE = 100

    /**
     * Process-wide REST client reused across calls.
     *
     * `HttpClient` (wrapped by [TrafficSimRestClient]) pools its connections and is meant to be
     * shared; building a fresh instance per call (as the initial implementation did) paid for a new
     * TCP/TLS handshake to the coupling server on every fetch, including every "Welten
     * aktualisieren" click. Reusing one instance lets repeated fetches reuse the existing
     * connection.
     */
    private val sharedClient: TrafficSimRestClient by lazy { TrafficSimRestClient(ConfigManager.loadNetworkConfig()) }

    /**
     * Loads the server world list, mapping each [WorldPropertiesDTO] to a selection-menu row.
     *
     * The server returns worlds oldest-first (creation order), which made recently created worlds
     * sink to the bottom of a list that can hold several hundred entries, forcing a very long
     * scroll to reach them. Rows are displayed newest-first instead, so the most recently created
     * world is always row 1 in the list. The "Welt N" number keeps counting from the server's
     * original oldest-first order (the oldest world is "Welt 1"), so a world's number stays stable
     * as new worlds are created, even though its row position shifts down the (still newest-first)
     * list.
     *
     * Any connection failure, non-success HTTP status, or malformed response (see the robustness
     * requirements from issue #210 "Robustheit bei Verbindungsabbruch") is caught and turned into
     * [ServerWorldsResult.Failure] instead of propagating, so the caller can show a message
     * without crashing.
     *
     * @param config network configuration; when [ConfigManager.NetworkConfig.active] is false, no
     *   request is sent and [SERVER_DISABLED_MESSAGE] is returned instead, regardless of [connected].
     * @param connected whether the table is currently connected to the server (mirrors the
     *   "Verbinden"/"Trennen" state in [scenes.ServerMenuScene]); when false, no request is sent
     *   and [NOT_CONNECTED_MESSAGE] is returned instead.
     * @param client REST client used to reach the coupling server; defaults to [sharedClient] so
     *   production callers reuse pooled connections, while tests can inject a client pointed at a
     *   local test server.
     * @return the fetched world's newest first, numbered by creation order, or a failure with a
     *   user-facing message.
     */
    fun loadWorlds(
        config: ConfigManager.NetworkConfig = ConfigManager.loadNetworkConfig(),
        connected: Boolean = ServerConnection.connectionState == ConnectionState.CONNECTED,
        client: TrafficSimRestClient = sharedClient
    ): ServerWorldsResult {
        if (!config.active) return ServerWorldsResult.Failure(SERVER_DISABLED_MESSAGE)
        if (!connected) return ServerWorldsResult.Failure(NOT_CONNECTED_MESSAGE)

        return try {
            val numberedOldestFirst = client.getWorlds().mapIndexed(::toWorldEntry)
            ServerWorldsResult.Success(numberedOldestFirst.asReversed())
        } catch (_: IOException) {
            ServerWorldsResult.Failure(CONNECTION_ERROR_MESSAGE)
        }
    }

    /**
     * Deletes one world on the server.
     *
     * Mirrors the guard checks in [loadWorlds]: when coupling is disabled or the table is not
     * connected, no request is sent and a matching failure message is returned instead. Any
     * connection failure or non-success HTTP status (see the robustness requirements from issue
     * #210 "Robustheit bei Verbindungsabbruch") is caught and turned into
     * [ServerWorldDeleteResult.Failure] instead of propagating, so the caller can show a message
     * without crashing.
     *
     * @param worldId ID of the world to delete.
     * @param config network configuration; when [ConfigManager.NetworkConfig.active] is false, no
     *   request is sent and [SERVER_DISABLED_MESSAGE] is returned instead, regardless of [connected].
     *   [ConfigManager.NetworkConfig.worldDeleteToken] is sent as the delete token, so only worlds
     *   created by this team (see [createWorld]) can actually be deleted through it.
     * @param connected whether the table is currently connected to the server.
     * @param client REST client used to reach the coupling server.
     * @return [ServerWorldDeleteResult.Success], or a failure with a user-facing message.
     */
    fun deleteWorld(
        worldId: String,
        config: ConfigManager.NetworkConfig = ConfigManager.loadNetworkConfig(),
        connected: Boolean = ServerConnection.connectionState == ConnectionState.CONNECTED,
        client: TrafficSimRestClient = TrafficSimRestClient(config)
    ): ServerWorldDeleteResult {
        if (!config.active) return ServerWorldDeleteResult.Failure(SERVER_DISABLED_MESSAGE)
        if (!connected) return ServerWorldDeleteResult.Failure(NOT_CONNECTED_MESSAGE)

        return try {
            client.deleteWorld(worldId, worldDeleteToken = config.worldDeleteToken)
            ServerWorldDeleteResult.Success
        } catch (_: IOException) {
            ServerWorldDeleteResult.Failure(DELETE_ERROR_MESSAGE)
        }
    }

    /**
     * Creates a new world on the server using [NEW_WORLD_COLUMNS]x[NEW_WORLD_ROWS] fields of
     * [NEW_WORLD_FIELD_SIZE] each, tagged with [ConfigManager.NetworkConfig.worldDeleteToken] so
     * this team can later delete it via [deleteWorld].
     *
     * Mirrors the guard checks in [loadWorlds]: when coupling is disabled or the table is not
     * connected, no request is sent and a matching failure message is returned instead. Any
     * connection failure or non-success HTTP status is caught and turned into
     * [ServerWorldCreateResult.Failure] instead of propagating, so the caller can show a message
     * without crashing.
     *
     * @param config network configuration; when [ConfigManager.NetworkConfig.active] is false, no
     *   request is sent and [SERVER_DISABLED_MESSAGE] is returned instead, regardless of [connected].
     * @param connected whether the table is currently connected to the server.
     * @param client REST client used to reach the coupling server.
     * @return [ServerWorldCreateResult.Success] with the new world's ID, or a failure with a
     *   user-facing message.
     */
    fun createWorld(
        config: ConfigManager.NetworkConfig = ConfigManager.loadNetworkConfig(),
        connected: Boolean = ServerConnection.connectionState == ConnectionState.CONNECTED,
        client: TrafficSimRestClient = TrafficSimRestClient(config)
    ): ServerWorldCreateResult {
        if (!config.active) return ServerWorldCreateResult.Failure(SERVER_DISABLED_MESSAGE)
        if (!connected) return ServerWorldCreateResult.Failure(NOT_CONNECTED_MESSAGE)

        return try {
            val response = client.createWorld(
                CreateWorldDTO(
                    columns = NEW_WORLD_COLUMNS,
                    rows = NEW_WORLD_ROWS,
                    fieldHeight = NEW_WORLD_FIELD_SIZE,
                    fieldWidth = NEW_WORLD_FIELD_SIZE,
                    deleteToken = config.worldDeleteToken
                )
            )
            ServerWorldCreateResult.Success(response.worldId)
        } catch (_: IOException) {
            ServerWorldCreateResult.Failure(CREATE_ERROR_MESSAGE)
        }
    }

    /**
     * Maps one server world to a selection-menu row.
     *
     * Server-provided display metadata is used when available. Older server responses without a
     * name still fall back to the world ID until local metadata can enrich the row.
     *
     * @param index position of [dto] in the server's original oldest-first list; used as the
     *   user-facing world number, so the oldest world is always "Welt 1" regardless of row order.
     * @param dto world metadata returned by the server.
     */
    private fun toWorldEntry(index: Int, dto: WorldPropertiesDTO): WorldSelectionScene.WorldEntry =
        WorldSelectionScene.WorldEntry(
            id = dto.worldId,
            number = index + 1,
            name = dto.name?.trim()?.takeIf { it.isNotEmpty() } ?: dto.worldId,
            source = "Server",
            columns = dto.columns,
            rows = dto.rows,
            levelSelection = dto.templateLevelId?.let { WorldLevelSelection.PredefinedLevel(it) }
        )
}
