package simulation
import domain.*
import domain.GameSimulationConfig.TRAFFIC_FLOW_OVERLOADED_MAX_UTILIZATION_THRESHOLD
import domain.GameSimulationConfig.TRAFFIC_FLOW_OVERLOADED_AVERAGE_UTILIZATION_THRESHOLD
import domain.GameSimulationConfig.TRAFFIC_FLOW_EFFICIENT_AVERAGE_UTILIZATION_THRESHOLD
import domain.GameSimulationConfig.TRAFFIC_FLOW_OVERLOADED_AVERAGE_SPEED_KMH_THRESHOLD
import domain.GameSimulationConfig.TRAFFIC_FLOW_EFFICIENT_AVERAGE_SPEED_KMH_THRESHOLD
import domain.GameSimulationConfig.TRAFFIC_FLOW_EFFICIENT_ARRIVAL_RATIO_THRESHOLD

/**
 * Collects statistics for the simulation.
 *
 * @property simulation The simulation instance.
 */
class StatisticsCollector(private val simulation: Simulation) {
    /** Simulated seconds accumulated since this simulation instance started. */
    private var simulationDurationSeconds: Double = 0.0

    /** Sum of active vehicle speeds multiplied by simulated seconds. */
    private var accumulatedVehicleSpeedSeconds: Double = 0.0

    /** Sum of active vehicle counts multiplied by simulated seconds. */
    private var accumulatedActiveVehicleSeconds: Double = 0.0

    /**
     * Adds a time-weighted speed sample after the tick-updated movement and arrivals.
     * 
     * @param dt The time delta for this simulation step.
     */
    fun recordStatisticsSample(dt: Double) {
        if (dt <= 0.0) return
        simulationDurationSeconds += dt
        val activeVehicles = simulation.level.vehicles.size
        if (activeVehicles == 0) return

        accumulatedVehicleSpeedSeconds += simulation.level.vehicles.sumOf { it.currentSpeed } * dt
        accumulatedActiveVehicleSeconds += activeVehicles * dt
    }

    /**
     * Returns the detailed metrics collected for the current simulation run.
     * 
     * @return The simulation statistics.
     */
    fun statistics(): SimulationStatistics {
        return SimulationStatistics(
            generatedVehicles = generatedVehicles(),
            arrivedVehicles = arrivedVehicles(),
            averageSpeedKmh = averageSpeedKmh(),
            simulationDurationSeconds = simulationDurationSeconds,
            roadNetworkLengthMeters = roadNetworkLengthMeters(),
            trafficFlowRating = trafficFlowRating()
        )
    }

    /**
     * Counts all vehicles generated by source nodes.
     * 
     * @return The number of vehicles generated by source nodes.
     */
    private fun generatedVehicles(): Int =
        simulation.level.nodes.filterIsInstance<SourceNode>().sumOf { it.vehiclesGenerated }

    /**
     * Counts all vehicles that arrived at target nodes.
     * 
     * @return The number of vehicles that arrived at target nodes.
     */
    private fun arrivedVehicles(): Int =
        simulation.level.nodes.filterIsInstance<TargetNode>().sumOf { it.vehiclesArrived }

    /**
     * Calculates the time-weighted active-vehicle average speed in km/h.
     * 
     * @return The average speed in km/h.
     */
    private fun averageSpeedKmh(): Double {
        if (accumulatedActiveVehicleSeconds <= 0.0) return 0.0
        return (accumulatedVehicleSpeedSeconds / accumulatedActiveVehicleSeconds) / Simulation.KMH_TO_MS
    }

    /**
     * Calculates the total length of the street network in virtual metres.
     * 
     * @return The total length of the street network.
     */
    private fun roadNetworkLengthMeters(): Double =
        simulation.level.streets.sumOf { SimulationUtils.streetLengthM(it.path) }

    /**
     * Classifies traffic flow from congestion detection, utilization, throughput, and speed.
     *
     * The rating combines four documented factors:
     *  - hard congestion signals (congestionDetected);
     *  - current street utilization, using maximum and network average thresholds;
     *  - throughput, measured as arrived/generated vehicle ratio;
     *  - average speed in km/h, using fixed thresholds that match the value shown to users.
     * 
     * @return The traffic flow rating.
     */
    private fun trafficFlowRating(): TrafficFlowRating {
        val generated = generatedVehicles()
        val arrived = arrivedVehicles()
        val arrivalRatio = if (generated > 0) arrived.toDouble() / generated else 0.0
        val averageUtilization = simulation.level.streets.map { it.utilization }.average().takeIf { it.isFinite() } ?: 0.0
        val maximumUtilization = simulation.level.streets.maxOfOrNull { it.utilization } ?: 0.0
        val averageSpeedKmh = averageSpeedKmh()
        val hasSpeedSamples = accumulatedActiveVehicleSeconds > 0.0

        return when {
            simulation.congestionDetected ||
                    maximumUtilization >= TRAFFIC_FLOW_OVERLOADED_MAX_UTILIZATION_THRESHOLD ||
                    averageUtilization >= TRAFFIC_FLOW_OVERLOADED_AVERAGE_UTILIZATION_THRESHOLD ||
                    (hasSpeedSamples &&
                        averageSpeedKmh < TRAFFIC_FLOW_OVERLOADED_AVERAGE_SPEED_KMH_THRESHOLD) -> {
                TrafficFlowRating.OVERLOADED
            }
            generated > 0 &&
                    arrivalRatio >= TRAFFIC_FLOW_EFFICIENT_ARRIVAL_RATIO_THRESHOLD &&
                    averageUtilization <= TRAFFIC_FLOW_EFFICIENT_AVERAGE_UTILIZATION_THRESHOLD &&
                    averageSpeedKmh >= TRAFFIC_FLOW_EFFICIENT_AVERAGE_SPEED_KMH_THRESHOLD -> {
                TrafficFlowRating.EFFICIENT
            }
            else -> TrafficFlowRating.STABLE
        }
    }
}
